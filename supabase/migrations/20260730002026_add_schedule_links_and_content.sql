## 1. New Table
- `exam_schedule_links` — month-based PDF schedule links shown on homepage
  and /exams page.
  - id (uuid pk), label (text, e.g. "Июль"), url (text, PDF link),
    published (bool), sort_order (int), created_at, updated_at.

## 2. Security
- RLS enabled on `exam_schedule_links`.
- anon/authenticated can SELECT published rows.
- authenticated can INSERT/UPDATE/DELETE (admin).

## 3. Data changes
- street_lists: DELETE old seed, INSERT 2 cities with real PDF URLs.
- settings: UPDATE telegram_url.
- useful_pages: UPDATE content for 6 existing slugs, INSERT 2 new slugs.
- exam_schedule_links: INSERT Июль and Август.
