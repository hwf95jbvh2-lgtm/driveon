-- ── exam_schedule_links table ───────────────────────────
CREATE TABLE IF NOT EXISTS exam_schedule_links (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  label text NOT NULL,
  url text NOT NULL,
  published boolean NOT NULL DEFAULT true,
  sort_order int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE exam_schedule_links ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public_select_exam_schedule_links" ON exam_schedule_links;
CREATE POLICY "public_select_exam_schedule_links" ON exam_schedule_links FOR SELECT
  TO anon, authenticated USING (published = true);

DROP POLICY IF EXISTS "admin_insert_exam_schedule_links" ON exam_schedule_links;
CREATE POLICY "admin_insert_exam_schedule_links" ON exam_schedule_links FOR INSERT
  TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "admin_update_exam_schedule_links" ON exam_schedule_links;
CREATE POLICY "admin_update_exam_schedule_links" ON exam_schedule_links FOR UPDATE
  TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "admin_delete_exam_schedule_links" ON exam_schedule_links;
CREATE POLICY "admin_delete_exam_schedule_links" ON exam_schedule_links FOR DELETE
  TO authenticated USING (true);

DROP TRIGGER IF EXISTS exam_schedule_links_updated_at ON exam_schedule_links;
CREATE TRIGGER exam_schedule_links_updated_at BEFORE UPDATE ON exam_schedule_links
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

